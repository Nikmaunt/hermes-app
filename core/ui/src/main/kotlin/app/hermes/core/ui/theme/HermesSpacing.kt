package app.hermes.core.ui.theme

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/**
 * One spacing scale for the whole app so padding/gaps stay on a grid instead of being
 * hand-picked per screen. Read as `HermesSpacing.md` etc.
 */
object HermesSpacing {
    val xs: Dp = 4.dp
    val sm: Dp = 8.dp
    val md: Dp = 12.dp
    val lg: Dp = 16.dp
    val xl: Dp = 24.dp
    val xxl: Dp = 32.dp
}
